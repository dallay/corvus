//! Integrator — generates Corvus-standard SKILL.md (with YAML frontmatter) from scout results.

use std::fs;
use std::path::PathBuf;

use anyhow::{bail, Context, Result};
use tracing::info;

use super::scout::ScoutResult;

// ---------------------------------------------------------------------------
// Integrator
// ---------------------------------------------------------------------------

pub struct Integrator {
    output_dir: PathBuf,
}

impl Integrator {
    pub fn new(output_dir: String) -> Self {
        Self {
            output_dir: PathBuf::from(output_dir),
        }
    }

    /// Write SKILL.md (with YAML frontmatter) for the given candidate.
    pub fn integrate(&self, candidate: &ScoutResult) -> Result<PathBuf> {
        let safe_name = sanitize_path_component(&candidate.name)?;
        let skill_dir = self.output_dir.join(&safe_name);
        fs::create_dir_all(&skill_dir)
            .with_context(|| format!("Failed to create dir: {}", skill_dir.display()))?;

        let md_path = skill_dir.join("SKILL.md");
        let md_content = self.generate_md(candidate);

        fs::write(&md_path, &md_content)
            .with_context(|| format!("Failed to write {}", md_path.display()))?;

        info!(
            skill = candidate.name.as_str(),
            path = %skill_dir.display(),
            "Integrated skill"
        );

        Ok(skill_dir)
    }

    // -- Generators ---------------------------------------------------------

    fn generate_md(&self, c: &ScoutResult) -> String {
        let lang = c.language.as_deref().unwrap_or("unknown");
        let tags_yaml = format!("  - discovered\n  - {lang}");
        format!(
            r#"---
name: {name}
description: {description}
version: 0.1.0
author: {owner}
tags:
{tags}
---

# {title}

> Auto-generated by SkillForge

{raw_description}

## Overview

- **Source**: [{url}]({url})
- **Owner**: {raw_owner}
- **Language**: {lang}
- **Stars**: {stars}
- **License**: {license}

## Usage

```bash
corvus skills install {raw_name}
```

## Notes

This manifest was auto-generated from repository metadata.
Review before enabling in production.
"#,
            name = yaml_escape(&c.name),
            description = yaml_escape(&c.description),
            owner = yaml_escape(&c.owner),
            tags = tags_yaml,
            title = c.name,
            raw_description = c.description,
            url = c.url,
            raw_owner = c.owner,
            raw_name = c.name,
            lang = lang,
            stars = c.stars,
            license = if c.has_license { "yes" } else { "unknown" },
        )
    }
}

/// Escape a string for safe inclusion in YAML frontmatter values.
fn yaml_escape(s: &str) -> String {
    if s.contains(':') || s.contains('#') || s.contains('\n') || s.contains('"') {
        format!("\"{}\"", s.replace('"', "\\\""))
    } else {
        s.to_string()
    }
}

/// Sanitize a string for use as a single path component.
/// Rejects empty names, "..", and names containing path separators or NUL.
fn sanitize_path_component(name: &str) -> Result<String> {
    let trimmed = name.trim().trim_matches('.');
    if trimmed.is_empty() {
        bail!("Skill name is empty or only dots after sanitization");
    }
    let sanitized: String = trimmed
        .chars()
        .map(|c| match c {
            '/' | '\\' | '\0' => '_',
            _ => c,
        })
        .collect();
    if sanitized == ".." || sanitized.contains('/') || sanitized.contains('\\') {
        bail!("Skill name '{}' is unsafe as a path component", name);
    }
    Ok(sanitized)
}

